// Creates deploy/dev/.env and portal/.env.local with random development
// secrets if they do not exist yet. Never prints secret values. Never
// changes an existing value: for an existing deploy/dev/.env it only appends
// keys that are missing (for example a new dev user's password).
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const secret = () => randomBytes(24).toString('hex');

const devEnv = join(root, 'deploy', 'dev', '.env');
const values = {
  RECAFCO_DEV_MAYAN_PORT: () => '8091',
  RECAFCO_DEV_DB_PASSWORD: secret,
  RECAFCO_DEV_REDIS_PASSWORD: secret,
  RECAFCO_DEV_PASSWORD_EMPLOYEE_A: secret,
  RECAFCO_DEV_PASSWORD_EMPLOYEE_B: secret,
  RECAFCO_DEV_PASSWORD_CONTROLLER: secret,
  RECAFCO_DEV_PASSWORD_ADMIN: secret,
};
if (existsSync(devEnv)) {
  const present = new Set(
    readFileSync(devEnv, 'utf8')
      .split(/\r?\n/)
      .map((line) => /^([A-Z0-9_]+)=/.exec(line)?.[1])
      .filter(Boolean),
  );
  const missing = Object.keys(values).filter((key) => !present.has(key));
  if (missing.length === 0) {
    console.log('deploy/dev/.env already complete - left unchanged.');
  } else {
    appendFileSync(devEnv, missing.map((key) => `${key}=${values[key]()}`).join('\n') + '\n');
    console.log(`deploy/dev/.env: added ${missing.join(', ')} (values not shown).`);
  }
} else {
  writeFileSync(
    devEnv,
    '# Generated by scripts/dev-env.mjs. Development only. Do not commit.\n' +
      Object.entries(values).map(([k, make]) => `${k}=${make()}`).join('\n') + '\n',
    { mode: 0o600 },
  );
  console.log('Created deploy/dev/.env (values not shown).');
}

const portalEnv = join(root, 'portal', '.env.local');
if (existsSync(portalEnv)) {
  console.log('portal/.env.local already exists - left unchanged.');
} else if (existsSync(join(root, 'portal'))) {
  writeFileSync(
    portalEnv,
    [
      '# Generated by scripts/dev-env.mjs. Development only. Do not commit.',
      'MAYAN_URL=http://127.0.0.1:8091',
      'PORTAL_SESSION_IDLE_MINUTES=30',
      'PORTAL_SESSION_ABSOLUTE_HOURS=8',
      'PORTAL_MAX_UPLOAD_MB=50',
      '',
    ].join('\n'),
    { mode: 0o600 },
  );
  console.log('Created portal/.env.local.');
}
