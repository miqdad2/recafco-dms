// Creates deploy/dev/.env and portal/.env.local with random development
// secrets. Never prints secret values. Never changes an existing value: for
// an existing file it only appends keys that are missing (for example a new
// dev user's password or the portal session key).
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const secret = () => randomBytes(24).toString('hex');
const header = '# Generated by scripts/dev-env.mjs. Development only. Do not commit.\n';

function ensureEnvFile(file, values) {
  const name = relative(root, file).replaceAll('\\', '/');
  if (!existsSync(file)) {
    writeFileSync(
      file,
      header + Object.entries(values).map(([key, make]) => `${key}=${make()}`).join('\n') + '\n',
      { mode: 0o600 },
    );
    console.log(`Created ${name} (values not shown).`);
    return;
  }
  const text = readFileSync(file, 'utf8');
  const present = new Set(
    text
      .split(/\r?\n/)
      .map((line) => /^([A-Z0-9_]+)=/.exec(line)?.[1])
      .filter(Boolean),
  );
  const missing = Object.keys(values).filter((key) => !present.has(key));
  if (missing.length === 0) {
    console.log(`${name} already complete - left unchanged.`);
    return;
  }
  const prefix = text.endsWith('\n') ? '' : '\n';
  appendFileSync(file, prefix + missing.map((key) => `${key}=${values[key]()}`).join('\n') + '\n');
  console.log(`${name}: added ${missing.join(', ')} (values not shown).`);
}

ensureEnvFile(join(root, 'deploy', 'dev', '.env'), {
  RECAFCO_DEV_MAYAN_PORT: () => '8091',
  RECAFCO_DEV_DB_PASSWORD: secret,
  RECAFCO_DEV_REDIS_PASSWORD: secret,
  RECAFCO_DEV_PASSWORD_EMPLOYEE_A: secret,
  RECAFCO_DEV_PASSWORD_EMPLOYEE_B: secret,
  RECAFCO_DEV_PASSWORD_CONTROLLER: secret,
  RECAFCO_DEV_PASSWORD_ADMIN: secret,
});

if (existsSync(join(root, 'portal'))) {
  ensureEnvFile(join(root, 'portal', '.env.local'), {
    MAYAN_URL: () => 'http://127.0.0.1:8091',
    PORTAL_SESSION_IDLE_MINUTES: () => '30',
    PORTAL_SESSION_ABSOLUTE_HOURS: () => '8',
    PORTAL_MAX_UPLOAD_MB: () => '50',
    // Encrypts Mayan tokens in the portal's session database.
    PORTAL_SESSION_KEY: () => randomBytes(32).toString('hex'),
  });
}
